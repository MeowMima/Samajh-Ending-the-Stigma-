@app.route("/api/recommend", methods=["POST"])
def recommend():
    """Get AI-generated recommendations and YouTube videos."""
    data = request.get_json()
    topic = data.get("topic", "").strip()

    if not topic:
        return jsonify({"error": "Please enter a topic."}), 400

    # Get tips from AI
    system_prompt = """You are a mental health education guide. Give warm, practical tips and resources.

Return ONLY valid JSON (no markdown) with this structure:
{
  "tips": ["tip1", "tip2", "tip3", "tip4"],
  "search_query": "a YouTube search query for educational videos on this topic",
  "context": "A 1-2 sentence warm introduction to this topic"
}"""

    messages = [
        {"role": "user", "content": f"Give me educational tips and resources about: {topic}"}
    ]

    response_text = call_llm(messages, system_prompt, max_tokens=400)

    try:
        clean = response_text.strip().replace("```json", "").replace("```", "").strip()
        ai_data = json.loads(clean)
    except:
        ai_data = {
            "tips": [
                "Take a moment to breathe deeply before exploring this topic",
                "Learning about mental health is an act of self-compassion",
                "Consider journaling your thoughts as you learn",
                "Remember: understanding is the first step"
            ],
            "search_query": f"{topic} mental health education",
            "context": f"Exploring {topic} is a meaningful step in your mental wellness journey."
        }

    # Fetch YouTube videos
    videos = []
    if YOUTUBE_API_KEY:
        search_query = ai_data.get("search_query", f"{topic} mental health")
        try:
            yt_url = "https://www.googleapis.com/youtube/v3/search"
            params = {
                "key": YOUTUBE_API_KEY,
                "q": search_query,
                "part": "snippet",
                "maxResults": 4,
                "type": "video",
                "videoEmbeddable": "true",
                "safeSearch": "strict",
                "relevanceLanguage": "en"
            }
            yt_response = requests.get(yt_url, params=params, timeout=10)
            yt_data = yt_response.json()
            for item in yt_data.get("items", []):
                videos.append({
                    "id": item["id"]["videoId"],
                    "title": item["snippet"]["title"],
                    "channel": item["snippet"]["channelTitle"],
                    "thumbnail": item["snippet"]["thumbnails"]["medium"]["url"]
                })
        except Exception as e:
            videos = []
    else:
        # Demo videos when no API key
        videos = [
            {
                "id": "inpok4MKVLM",
                "title": "What is a Mental Illness? - The Science",
                "channel": "SciShow Psych",
                "thumbnail": "https://img.youtube.com/vi/inpok4MKVLM/mqdefault.jpg"
            },
            {
                "id": "XiCrniLQGYc",
                "title": "How to Cope with Anxiety | Olivia Remes | TEDxUHasselt",
                "channel": "TED",
                "thumbnail": "https://img.youtube.com/vi/XiCrniLQGYc/mqdefault.jpg"
            }
        ]

    return jsonify({
        "topic": topic,
        "context": ai_data.get("context", ""),
        "tips": ai_data.get("tips", []),
        "videos": videos
    })

