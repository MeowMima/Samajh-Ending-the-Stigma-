@app.route("/api/journal/reflect", methods=["POST"])
def journal_reflect():
    """Analyze journal entry using AI and return reflections."""
    data = request.get_json()
    entry_text = data.get("text", "").strip()

    if not entry_text:
        return jsonify({"error": "Please write something first."}), 400

    if len(entry_text) < 20:
        return jsonify({"error": "Write a little more for a meaningful reflection."}), 400

    system_prompt = """You are Samajh's gentle reflection guide. You help people understand their own thoughts and emotions.

IMPORTANT RULES:
- Never diagnose or label mental health conditions
- Be warm, curious, and non-judgmental
- Speak like a wise, caring friend — not a therapist
- Focus on helping the person understand themselves better
- Keep responses concise and gentle

Return your response as valid JSON with these exact keys:
{
  "summary": "A 1-2 sentence gentle summary of what they shared",
  "emotions": "2-4 emotional themes you notice (e.g., 'feeling overwhelmed, searching for clarity')",
  "reflection": "A thoughtful 2-3 sentence reflection that helps them see their experience from a new angle",
  "suggestion": "One gentle, actionable suggestion (not clinical advice)"
}"""

    messages = [
        {"role": "user", "content": f"Here is my journal entry:\n\n{entry_text}\n\nPlease reflect on this gently."}
    ]

    response_text = call_llm(messages, system_prompt, max_tokens=600)

    # Try to parse JSON response
    try:
        # Clean up any markdown formatting
        clean = response_text.strip().replace("```json", "").replace("```", "").strip()
        result = json.loads(clean)
    except:
        # Fallback if LLM doesn't return valid JSON
        result = {
            "summary": "You shared something meaningful.",
            "emotions": "Mixed emotions, reflection",
            "reflection": "I'm here with you. Even writing this shows awareness.",
            "suggestion": "Take a slow breath and notice what stays with you."
            }
        
    # Save entry to database
    session_id = session.get("session_id", request.remote_addr)
    with get_db() as db:
        db.execute("""
            INSERT INTO journal_entries (session_id, content, ai_summary, ai_emotions, ai_reflection, ai_suggestion)
            VALUES (?, ?, ?, ?, ?, ?)
        """, (
            session_id,
            entry_text,
            result.get("summary", ""),
            result.get("emotions", ""),
            result.get("reflection", ""),
            result.get("suggestion", "")
        ))
        db.commit()

    return jsonify(result)

