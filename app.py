@app.route("/api/chat", methods=["POST"])
def chat():
    """Saathi chatbot endpoint"""
    data = request.get_json()
    user_message = data.get("message", "").strip()
    history = data.get("history", [])  # Previous messages from frontend

    if not user_message:
        return jsonify({"error": "Please say something."}), 400

    # Crisis detection keywords
    crisis_keywords = [
        "suicide", "kill myself", "end my life", "don't want to live",
        "self harm", "hurt myself", "can't go on", "no reason to live"
    ]
    is_crisis = any(kw in user_message.lower() for kw in crisis_keywords)

    system_prompt = """You are Saathi — a warm, empathetic AI companion on the Samajh mental health education platform.

YOUR PERSONALITY:
- Warm, gentle, and genuinely curious about people
- Like a thoughtful friend who really listens
- Non-judgmental, never clinical or diagnostic
- You help people feel heard and less alone

YOUR RULES:
- NEVER diagnose any mental health condition
- NEVER give medical advice
- Keep responses SHORT — 2-4 sentences max
- Ask one curious follow-up question when appropriate
- If someone seems in crisis, gently point them to professional help
- You can discuss mental health education topics warmly

Remember: you're an educational companion, not a therapist."""

    # Build message list for API
    messages = []
    for msg in history[-8:]:  # Last 8 messages for context
        messages.append({"role": msg["role"], "content": msg["content"]})
    messages.append({"role": "user", "content": user_message})

    response_text = call_llm(messages, system_prompt, max_tokens=200)

    # Append crisis helpline if detected
    crisis_info = None
    if is_crisis:
        crisis_info = {
            "message": "I hear you, and I'm glad you're talking. Please reach out to a crisis helpline right now.",
            "helplines": [
                {"name": "iCall (India)", "number": "9152987821"},
                {"name": "Vandrevala Foundation", "number": "1860-2662-345"},
                {"name": "AASRA", "number": "9820466627"}
            ]
        }

    return jsonify({
        "response": response_text,
        "crisis": crisis_info
    })

