@app.route("/api/article/<topic>", methods=["GET"])
def generate_article(topic):
    """Generate educational article content using AI."""
    topic_map = {
        "history": "the fascinating history of mental health understanding — from ancient beliefs to modern science",
        "anxiety": "anxiety disorders explained simply, with compassion and clarity",
        "depression": "understanding depression — what it really is, how it feels, and how people find their way through",
        "stigma": "breaking the stigma around mental health — why it exists and how we can change it",
        "caregivers": "the impact of mental health challenges on caregivers and loved ones",
        "stories": "real stories of people navigating mental health challenges with courage",
        "research": "the latest fascinating research in mental health science",
        "mindfulness": "mindfulness and mental wellness — what the science actually says",
        "burnout": "understanding burnout — the modern epidemic of exhaustion",
        "relationships": "how mental health shapes and is shaped by our relationships"
    }

    description = topic_map.get(topic, f"the topic of {topic.replace('-', ' ')}")

    system_prompt = """You are an educational writer for Samajh, a mental health education platform.

Write warm, accessible, engaging content about mental health — like a compassionate science journalist.

RULES:
- Never diagnose or give clinical advice
- Write for general audience — no jargon
- Be hopeful and destigmatizing in tone
- Use real examples (anonymized) when helpful
- Structure: intro paragraph, 3-4 sections with headings, closing thought
- Return clean HTML using: <h2>, <p>, <blockquote>, <ul>, <li> tags only"""

    messages = [
        {"role": "user", "content": f"Write a warm, educational article about {description}. Make it engaging, compassionate, and informative. About 500-700 words."}
    ]

    content = call_llm(messages, system_prompt, max_tokens=1000)

    return jsonify({"topic": topic, "content": content})

